async def seed() -> None:
    """Создаёт схему и наполняет таблицу отелей, если она пуста."""
    await init_db()
    async with aiosqlite.connect(config.db_path) as db:
        async with db.execute("SELECT COUNT(*) FROM hotels") as cursor:
            (count,) = await cursor.fetchone()
        if count > 0:
            print(f"База уже содержит {count} отелей — пропускаю заполнение.")
            return

        await db.executemany(
            """
            INSERT INTO hotels
                (name, city, price, stars, rating, capacity,
                 amenities, near_sea, description, image)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            [
                (
                    name, city, price, stars, rating, capacity,
                    json.dumps(amenities, ensure_ascii=False),
                    1 if near_sea else 0, description, image,
                )
                for (name, city, price, stars, rating, capacity,
                     amenities, near_sea, description, image) in HOTELS
            ],
        )
        await db.commit()
        print(f"Добавлено отелей: {len(HOTELS)}")


if __name__ == "__main__":
    import asyncio

    asyncio.run(seed())
